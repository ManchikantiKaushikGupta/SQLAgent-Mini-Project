"""
Evaluation Metrics Schemas

Defines structured Pydantic models for representing test cases,
single execution results, and aggregate benchmark run summaries.
"""

from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any

class BenchmarkCase(BaseModel):
    """
    Represents a single test case in the evaluation suite.
    """
    id: str = Field(..., description="Unique identifier for the benchmark case")
    query: str = Field(..., description="The natural language query to run")
    reference_sql: str = Field(..., description="The ground truth SQL query")
    difficulty: str = Field("simple", description="Difficulty tier: simple, medium, complex")
    order_sensitive: bool = Field(False, description="Whether row ordering is semantically critical for correctness")

class BenchmarkResult(BaseModel):
    """
    Represents the evaluation results of a single benchmark case.
    """
    case_id: str = Field(..., description="Identifier of the benchmark case")
    query: str = Field(..., description="The natural language query evaluated")
    reference_sql: str = Field(..., description="The reference SQL query")
    generated_sql: Optional[str] = Field(None, description="The SQL query generated by the agent pipeline")
    success: bool = Field(..., description="Whether execution accuracy is 100% (matching reference results)")
    error_message: Optional[str] = Field(None, description="Any execution or validation error message")
    latency_seconds: float = Field(..., description="Time taken to process the query from graph entry to end")
    prompt_tokens: int = Field(0, description="Number of tokens used in LLM prompts")
    completion_tokens: int = Field(0, description="Number of tokens generated by LLM completions")
    total_tokens: int = Field(0, description="Total number of LLM tokens used")
    retry_count: int = Field(0, description="The number of correction attempts made by the agent")
    corrected_successfully: bool = Field(False, description="True if it failed initially but was successfully corrected")
    initial_sql_valid: bool = Field(True, description="True if the initial generated SQL passed safety/syntax validation without correction")
    expected_rows: int = Field(0, description="Number of rows returned by the reference SQL")
    returned_rows: int = Field(0, description="Number of rows returned by the generated SQL")

class BenchmarkSummary(BaseModel):
    """
    Represents the aggregate metrics over the entire benchmark suite run.
    """
    run_id: str = Field(..., description="Unique identifier for this benchmark run")
    timestamp: str = Field(..., description="Timestamp of when the benchmark run completed")
    total_cases: int = Field(..., description="Total number of test cases evaluated")
    passed_cases: int = Field(..., description="Number of test cases that matched the reference execution results")
    failed_cases: int = Field(..., description="Number of test cases that did not match or encountered errors")
    execution_accuracy_pct: float = Field(..., description="Percentage of queries with correct execution results")
    average_latency_seconds: float = Field(..., description="Average latency across all cases")
    total_tokens: int = Field(..., description="Total tokens consumed across all cases")
    avg_tokens_per_query: float = Field(..., description="Average token consumption per query")
    total_retries: int = Field(0, description="Total number of correction loop runs across all queries")
    queries_needing_correction: int = Field(0, description="Number of queries that triggered at least one retry")
    queries_corrected_successfully: int = Field(0, description="Number of queries that failed initially but were corrected successfully")
    correction_success_rate_pct: float = Field(0.0, description="Percentage of initially failed queries that were successfully corrected")
    difficulty_breakdown: Dict[str, Dict[str, Any]] = Field(default_factory=dict, description="Execution accuracy stats broken down by difficulty tier")
